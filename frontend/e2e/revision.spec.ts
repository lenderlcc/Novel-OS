import { expect, test, type Page } from '@playwright/test'

async function prepareRevision(page: Page, marker = '') {
  await page.goto('/')
  await page.getByText('＋ 新建项目', { exact: true }).click()
  await page.getByLabel('项目名称', { exact: true }).fill(`Revision ${Date.now()}`)
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.locator('#project')).not.toHaveValue('')
  await page.getByRole('button', { name: '写作偏好', exact: true }).click()
  await page.getByText('编辑', { exact: true }).click()
  await page.getByLabel('叙事人称').selectOption('THIRD_PERSON')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await page.getByRole('button', { name: '批准 Profile v1' }).click()
  await expect(page.getByText('当前 v1 · 已批准 v1')).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByText('＋ 新建章节', { exact: true }).click()
  await page.getByLabel('章节标题', { exact: true }).fill('雨夜来信')
  await page.getByRole('button', { name: '创建章节', exact: true }).click()
  await page.getByLabel('章节需求').fill(`两人在雨夜会合，约定沿河寻找失落的信件。不要新增核心能力。[E2E:REVISION]${marker}`)
  await page.getByRole('button', { name: '生成方案', exact: true }).click()
  await expect(page.getByTestId('human-gate')).toBeVisible()
  await page.getByRole('button', { name: '批准并开始写作' }).click()
  await expect(page.getByRole('button', { name: '根据审阅修改', exact: true })).toBeVisible()
  return page.getByLabel('章节正文', { exact: true }).textContent()
}

test('explicit revision creates v2, re-reviews once, preserves v1 and stops even on FAIL', async ({ page }) => {
  const original = await prepareRevision(page)
  await expect(page.getByText('Review v1 · 对应 Draft v1', { exact: true })).toBeVisible()
  const accepted = page.waitForResponse(r => r.url().endsWith('/revision') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '根据审阅修改', exact: true }).click()
  expect((await accepted).status()).toBe(200)
  await page.reload()
  await expect(page.getByText('Review v2 · 对应 Draft v2', { exact: true })).toBeVisible()
  await expect(page.getByTestId('draft')).toContainText('Draft v2')
  await expect(page.getByRole('heading', { name: '等待确认修改', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '根据审阅修改', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/novel010b-revision-workspace.png', fullPage: true })
  await page.getByLabel('正文版本', { exact: true }).selectOption('1')
  await expect(page.getByLabel('章节正文', { exact: true })).toHaveText(original!)
  await expect(page.getByText('Review v1 · 对应 Draft v1', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '根据审阅修改', exact: true })).toHaveCount(0)
  await page.getByLabel('正文版本', { exact: true }).selectOption('2')
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(page.getByTestId('draft')).toContainText('Draft v2')
  await page.getByRole('button', { name: 'Debug', exact: true }).click()
  await page.getByText('Revision / Lineage', { exact: true }).click()
  await expect(page.locator('#debug-section')).toContainText('revision_plan_id')
  await expect(page.locator('#debug-section')).toContainText('content_hash')
})


test('fidelity failure keeps v1 and exposes rejected candidate without retry', async ({ page }) => {
  const original = await prepareRevision(page, '[E2E:FIDELITY_FAIL]')
  await page.getByRole('button', { name: '根据审阅修改', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '这次修改范围过大，未替换当前正文。' })).toBeVisible()
  await expect(page.getByLabel('章节正文', { exact: true })).toHaveText(original!)
  await expect(page.getByText('Review v1 · 对应 Draft v1', { exact: true })).toBeVisible()
  await page.getByText('查看详情', { exact: true }).click()
  await expect(page.getByText('查看未采用的修改稿', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(page.getByLabel('章节正文', { exact: true })).toHaveText(original!)
  await expect(page.getByRole('button', { name: '继续执行', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Debug', exact: true }).click()
  await page.getByText('Revision / Lineage', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Source Fidelity: FAIL', exact: true })).toBeVisible()
  await expect(page.locator('#debug-section')).toContainText('UNAUTHORIZED_SCENE_REPLACEMENT')
  await expect(page.locator('#debug-section')).toContainText('REVISION ZONES')
  await page.screenshot({ path: '/tmp/novel010b-fidelity-rejected.png', fullPage: true })
})
