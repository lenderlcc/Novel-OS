import { expect, test } from '@playwright/test'

test('narrative perspective saves a draft, survives reload, and needs explicit approval', async ({ page }) => {
  await page.goto('/')
  await page.getByText('＋ 新建项目', { exact: true }).click()
  await page.getByLabel('项目名称', { exact: true }).fill(`Perspective ${Date.now()}`)
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.locator('#project')).not.toHaveValue('')
  const project = await page.locator('#project').inputValue()
  const state = async () => (await page.request.get(`/api/v1/projects/${project}/writing-profile`)).json()
  await page.getByRole('button', { name: '写作偏好', exact: true }).click()
  await page.getByText('编辑', { exact: true }).click()
  await expect(page.getByLabel('叙事人称')).toBeEnabled()
  await page.getByLabel('叙事人称').selectOption('THIRD_PERSON')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByRole('button', { name: '批准 Profile v1' })).toBeEnabled()
  expect((await state()).approved).toBeNull()
  await page.reload()
  await page.getByRole('button', { name: '写作偏好', exact: true }).click()
  await page.getByText('编辑', { exact: true }).click()
  await expect(page.getByLabel('叙事人称')).toHaveValue('THIRD_PERSON')
  await page.getByRole('button', { name: '批准 Profile v1' }).click()
  await expect(page.getByText('当前 v1 · 已批准 v1')).toBeVisible()
  const approved = (await state()).approved
  expect(approved.narrative_perspective).toBe('THIRD_PERSON')
  expect(approved.authority_level).toBe('A5_USER_PREFERENCE')
  await page.getByLabel('叙事人称').selectOption('FIRST_PERSON')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByText('当前 v2 · 已批准 v1')).toBeVisible()
  expect((await state()).approved).toEqual(approved)
  await expect(page.locator('.profile-summary')).toContainText('第三人称')
  await page.screenshot({ path: test.info().outputPath('perspective-draft-isolation.png'), fullPage: true })
  await page.getByRole('button', { name: '批准 Profile v2' }).click()
  await expect(page.locator('.profile-summary')).toContainText('第一人称')
  expect((await state()).approved.narrative_perspective).toBe('FIRST_PERSON')
})
